/// Get a random message index
pub fn random_message_index() -> usize {
    use std::time::{SystemTime, UNIX_EPOCH};
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .subsec_nanos() as usize;
    nanos % FUNNY_MESSAGES.len()
}

/// Get a different random message index (not the same as current)
pub fn different_random_index(current: usize) -> usize {
    if FUNNY_MESSAGES.len() <= 1 {
        return 0;
    }
    let mut new_index = random_message_index();
    // Simple retry if we got the same index
    if new_index == current {
        new_index = (new_index + 1) % FUNNY_MESSAGES.len();
    }
    new_index
}
